#!/usr/bin/env node
// Writes app/<page>/i18n/index.ts: one lazy loader per copy file present
// (2026-10-17). Run from web/: node scripts/landing/gen-i18n-index.mjs
import { readdirSync, writeFileSync } from "node:fs";
const PAGES = [["individuals", "IndCopy", "IND_LOADERS"], ["schools", "SchCopy", "SCH_LOADERS"], ["families", "FamI18n", "FAM_LOADERS"]];
for (const [page, type, name] of PAGES) {
  let files;
  try { files = readdirSync(`src/app/${page}/i18n`); } catch { continue; }
  const langs = files.filter((f) => f.endsWith(".ts") && !["types.ts", "index.ts", "load.ts"].includes(f)).map((f) => f.slice(0, -3)).sort();
  const lines = langs.map((l) => `  ${/^[a-z]+$/.test(l) ? l : JSON.stringify(l)}: () => import("./${l}"),`);
  writeFileSync(`src/app/${page}/i18n/index.ts`, `// Generated by scripts/landing/gen-i18n-index.mjs: one lazy loader per language file.
import type { ${type} } from "./types";
import type { CopyLoaders } from "@/lib/landing-i18n-client";

export const ${name}: CopyLoaders<${type}> = {
${lines.join("\n")}
};

/** The copy of a language on the server, and the language it is in (English when there is no file). */
export async function load${type}(lang: string): Promise<{ lang: string; copy: ${type} }> {
  const own = !!${name}[lang];
  return { lang: own ? lang : "en", copy: (await (own ? ${name}[lang] : ${name}.en)()).default };
}
`);
  console.log(`${page}: ${langs.length} languages`);
}
