import type { WorldCopy, WorldKey } from "./world-i18n";

/**
 * World game copy in the other UI languages (Gadi 2026-10-30).
 * Kid-facing, short and warm. No dashes anywhere; "Gadit" stays Latin.
 */

/** [title, enter, my, arrived label (ends with a colon), newArea, location phrase for wordsIn] */
type Row = [string, string, string, string, string, string];

function worlds(
  empty: string,
  words: (n: number, loc: string) => string,
  rows: Record<WorldKey, Row>,
): WorldCopy["worlds"] {
  const out = {} as WorldCopy["worlds"];
  for (const k of Object.keys(rows) as WorldKey[]) {
    const [title, enter, my, arrived, newArea, loc] = rows[k];
    out[k] = {
      title,
      enter,
      my,
      // Full-width colon (CJK) takes no space after it.
      arrived: (w) => (arrived.endsWith("：") ? `${arrived}${w}` : `${arrived} ${w}`),
      newArea,
      wordsIn: (n) => words(n, loc),
      empty,
    };
  }
  return out;
}

/** Russian / Ukrainian: 1, 21, 31 / 2-4, 22-24 / 5-20, 25-30 */
const eastSlavic = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};
/** Polish: 1 / 2-4, 22-24 (not 12-14) / everything else */
const polish = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};
/** Czech / Slovak: 1 / 2-4 / 5+ */
const westSlavic = (n: number, one: string, few: string, many: string) =>
  n === 1 ? one : n >= 2 && n <= 4 ? few : many;
/** Arabic: 1 / 2 / 3-10 / 11+ */
const arWords = (n: number) => {
  if (n === 1) return "كلمة واحدة";
  if (n === 2) return "كلمتان";
  const m100 = n % 100;
  if (m100 >= 3 && m100 <= 10) return `${n} كلمات`;
  return `${n} كلمة`;
};

