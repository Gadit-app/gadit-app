// helper: resolves a t() per locale, with EN fallback for missing keys
function makeT(locale) {
  const base = STRINGS.en;
  const loc = STRINGS[locale] || base;
  return (key, ...args) => {
    const val = loc[key] ?? base[key];
    return typeof val === 'function' ? val(...args) : val;
  };
}

